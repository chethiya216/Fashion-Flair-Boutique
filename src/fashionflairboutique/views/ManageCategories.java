    public ManageCategories(User loggedInUser) {
        initComponents();
        this.currentUser = loggedInUser;
        this.categoryDAO = new CategoryDAO();
        

        // 1. Setup Status ComboBox Options
        initStatusComboBox();

        // 2. Display Header Details
        if (currentUser != null) {
            UIUtils.displayUserDetails(jLblShowUser, currentUser);
        }
        this.clockTimer = UIUtils.startLiveClock(jLblShowDate, jLblShowTime);

        // 3. Load Categories into Table
        loadCategoriesTable();

        // 4. Attach Sidebar
        if (this.currentUser != null) {
            jPanelsidebarPanelContainer.removeAll();
            jPanelsidebarPanelContainer.setLayout(new BorderLayout());

            SidebarPanel sidebar = new SidebarPanel(this, currentUser);
            jPanelsidebarPanelContainer.add(sidebar, BorderLayout.CENTER);

            jPanelsidebarPanelContainer.revalidate();
            jPanelsidebarPanelContainer.repaint();
        }
    }

    private void initStatusComboBox() {
        jCBStatus.removeAllItems();
        jCBStatus.addItem("Active");
        jCBStatus.addItem("Inactive");
        jCBStatus.setSelectedIndex(0); // Default to Active
    }

    private void loadCategoriesTable() {
        try {
            List<Category> list = categoryDAO.getAllCategories();
            DefaultTableModel model = (DefaultTableModel) jTableCategories.getModel();
            model.setRowCount(0);

            for (Category cat : list) {
                model.addRow(new Object[]{
                    cat.getCategoryId(),                                       // Col 0
                    cat.getCategoryName(),                                     // Col 1
                    cat.getDescription() != null ? cat.getDescription() : "",  // Col 2
                    cat.getStatus()                                            // Col 3
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading categories: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    
    private void clearForm() {
        selectedCategoryId = -1;
        jTFCName.setText("");
        jTADescription.setText("");
        jCBStatus.setSelectedIndex(0); // Reset to "Active"
        jTableCategories.clearSelection();
    }

    @Override
    public void dispose() {
        if (clockTimer != null && clockTimer.isRunning()) {
            clockTimer.stop();
        }
        super.dispose();
    }
