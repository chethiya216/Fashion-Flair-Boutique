    private void jBtnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnAddActionPerformed
        String name = jTFCName.getText().trim();
        String description = jTADescription.getText().trim();

        // Safely get status from JComboBox
        String status = jCBStatus.getSelectedItem() != null ? jCBStatus.getSelectedItem().toString() : "Active";

        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Category Name is required!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            if (categoryDAO.categoryNameExists(name, -1)) {
                JOptionPane.showMessageDialog(this, "Category name already exists!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Saves name, description, and status to Database
            if (categoryDAO.addCategory(name, description, status)) {
                JOptionPane.showMessageDialog(this, "Category added successfully!");
                clearForm();
                loadCategoriesTable(); // Reloads table to display status in Col 3
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Failed to add category: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBtnAddActionPerformed

    private void jBtnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnUpdateActionPerformed
        if (selectedCategoryId == -1) {
            JOptionPane.showMessageDialog(this, "Please select a category from the table to update.", "Selection Required", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String name = jTFCName.getText().trim();
        String description = jTADescription.getText().trim();
        String status = jCBStatus.getSelectedItem().toString(); // Reads selected value from JComboBox

        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Category Name cannot be empty!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            if (categoryDAO.categoryNameExists(name, selectedCategoryId)) {
                JOptionPane.showMessageDialog(this, "Another category with this name already exists!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            if (categoryDAO.updateCategory(selectedCategoryId, name, description, status)) {
                JOptionPane.showMessageDialog(this, "Category updated successfully!");
                clearForm();
                loadCategoriesTable();
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Failed to update category: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBtnUpdateActionPerformed

    private void jTableCategoriesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableCategoriesMouseClicked
        int selectedRow = jTableCategories.getSelectedRow();
        if (selectedRow != -1) {
            DefaultTableModel model = (DefaultTableModel) jTableCategories.getModel();
            selectedCategoryId = Integer.parseInt(model.getValueAt(selectedRow, 0).toString());
            jTFCName.setText(model.getValueAt(selectedRow, 1).toString());
            jTADescription.setText(model.getValueAt(selectedRow, 2).toString());

            // Select matching item in JComboBox
            String status = model.getValueAt(selectedRow, 3).toString();
            jCBStatus.setSelectedItem(status);
        }
    }//GEN-LAST:event_jTableCategoriesMouseClicked

