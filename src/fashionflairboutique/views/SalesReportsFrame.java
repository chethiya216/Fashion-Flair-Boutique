    private void loadTableData(){
        String[] columnNames = {"Sale ID", "Invoice No", "Cashier", "Discount", "Net Total", "Date & Time"};
        DefaultTableModel reportTable = new DefaultTableModel(columnNames, 0);

        try {
            SalesReportDAO dao = new SalesReportDAO();
            // Passing empty strings fetches all records by default
            List<SalesReport> results = dao.searchSales("", "");

            for (SalesReport sr : results) {
                Object[] row = new Object[] {
                    sr.getSaleId(),
                    sr.getInvoiceNumber(),
                    sr.getCashier(),
                    sr.getTotalDiscount(),
                    sr.getNetTotal(),
                    sr.getSaleDate()
                };
                reportTable.addRow(row);
            }

            jTable1.setModel(reportTable);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, 
                "Error loading sales report: " + e.getMessage(),
                "Database Error", 
                JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
        
        updateSummaryLabels();
    
    }
    
    private void updateSummaryLabels() {
        // Fetch metrics directly from database via DAO
        double totalRevenue = SalesReportDAO.getTotalRevenue();
        int totalTransactions = SalesReportDAO.getTotalTransactions();
        double avgOrderValue = SalesReportDAO.getAverageOrderValue();
        int totalItemsSold = SalesReportDAO.getTotalItemsSold();

        // Set text to the UI JLabels
        jLblTotalRevenue.setText(String.format("LKR %.2f", totalRevenue));
        jLblTotalTransactions.setText(String.valueOf(totalTransactions));
        jLblAverageOrderValue.setText(String.format("LKR %.2f", avgOrderValue));
        jLblTotalItemsSold.setText(String.valueOf(totalItemsSold));
    }

