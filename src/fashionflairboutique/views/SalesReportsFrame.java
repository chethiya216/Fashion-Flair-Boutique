    private void jBtnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnSearchActionPerformed
       
        String invoiceInput = jTFReferenceNo.getText();
        String dateInput = "";

        // Safely extract date if selected from JDateChooser
        if (jDateChooser.getDate() != null) {
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            dateInput = sdf.format(jDateChooser.getDate());
        }

        // 1. Define your table column headers
        String[] columnNames = {"Sale ID", "Invoice No", "Cashier", "Discount", "Net Total", "Date & Time"};

        // 2. Initialize the table model with the column headers
        DefaultTableModel reportTable = new DefaultTableModel(columnNames, 0);

        try {
            SalesReportDAO dao = new SalesReportDAO();
            List<SalesReport> results = dao.searchSales(invoiceInput, dateInput);

            // 3. Loop through each result and add rows to the model
            for (SalesReport sr : results) {
                Object[] row = new Object[] {
                    sr.getSaleId(),
                    sr.getInvoiceNumber(),
                    sr.getCashier(),
                    sr.getTotalDiscount(),
                    sr.getNetTotal(),
                    sr.getSaleDate()
                };
                reportTable.addRow(row);
            }

            // 4. CRITICAL: Set the populated model to your actual JTable on the form
            jTable1.setModel(reportTable);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, 
                "Error loading sales report: " + e.getMessage(),
                "Database Error", 
                JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
        
        
    }//GEN-LAST:event_jBtnSearchActionPerformed

